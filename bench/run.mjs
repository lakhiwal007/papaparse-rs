// Cross-implementation benchmark: PapaParse (JS) vs papaparse-rs (native and wasm).
// Prerequisites: `just bench-compare` builds everything and runs this script.
import { spawnSync } from 'node:child_process';
import { existsSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import os from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const ITERATIONS = Number(process.env.ITERATIONS ?? 5);
const TIMEOUT_MS = 10 * 60 * 1000;
const rustBin = process.env.PAPAPARSE_BENCH_BIN ?? join(here, '../target/release/papaparse-bench');

const impls = [
	{ name: 'PapaParse 5.7.0 (JS)', cmd: process.execPath, args: [join(here, 'runners/js.mjs')] },
	{ name: 'papaparse-rs (wasm, in Node)', cmd: process.execPath, args: [join(here, 'runners/wasm.mjs')] },
	{ name: 'papaparse-rs (napi-rs addon, in Node)', cmd: process.execPath, args: [join(here, 'runners/node.mjs')] },
	{ name: 'papaparse-rs (native)', cmd: rustBin, args: [] },
];
const cases = [
	{ file: 'simple.csv', label: 'simple.csv, auto-detect, arrays', config: {} },
	{ file: 'simple.csv', label: 'simple.csv, header + dynamicTyping', config: { header: true, dynamicTyping: true } },
	{ file: 'quoted.csv', label: 'quoted.csv, auto-detect, arrays', config: {} },
	{ file: 'quoted.csv', label: 'quoted.csv, header + dynamicTyping', config: { header: true, dynamicTyping: true } },
	{ file: 'pathological.csv', label: 'pathological.csv (single quoted column, 0.8 MB)', config: { delimiter: ',' }, iterations: 3 },
	{ file: 'quoted.csv', label: 'quoted.csv, header, row by row (`step`)', config: { header: true, mode: 'step' } },
	{ file: 'quoted.csv', label: 'quoted.csv, `unparse` of header + dynamicTyping rows', config: { header: true, dynamicTyping: true, mode: 'unparse' } },
];

/** Runs a command under the platform's `time` to capture peak RSS. */
function measure(cmd, args) {
	const mac = process.platform === 'darwin';
	const timeArgs = mac ? ['-l', cmd, ...args] : ['-v', cmd, ...args];
	const r = spawnSync('/usr/bin/time', timeArgs, { encoding: 'utf8', timeout: TIMEOUT_MS, maxBuffer: 1 << 26 });
	if (r.error?.code === 'ETIMEDOUT' || r.signal) return { timeout: true };
	if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed:\n${r.stderr}`);
	const rss = mac
		? Number(/(\d+)\s+maximum resident set size/.exec(r.stderr)?.[1])
		: Number(/Maximum resident set size \(kbytes\): (\d+)/.exec(r.stderr)?.[1]) * 1024;
	return { ...JSON.parse(r.stdout.trim().split('\n').pop()), rss };
}

const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];
const fmtMs = (ms) => (ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${ms.toFixed(0)} ms`);

for (const c of cases) {
	if (!existsSync(join(here, 'data', c.file))) throw new Error('run `node bench/gen-data.mjs` first');
}

const lines = [];
const env = `${os.cpus()[0].model}, ${os.cpus().length} cores, ${(os.totalmem() / 2 ** 30).toFixed(0)} GB RAM, ${os.platform()} ${os.release()}, Node ${process.version}`;
lines.push(`Environment: ${env}`, `Iterations: ${ITERATIONS} timed runs after 1 warm-up (median shown); peak RSS of the whole process.`, '');
lines.push('| Case | Implementation | Median | Throughput | vs JS | Peak RSS | Output check |');
lines.push('|---|---|---:|---:|---:|---:|---|');

for (const c of cases) {
	const path = join(here, 'data', c.file);
	const mb = statSync(path).size / 1e6;
	const iterations = String(c.iterations ?? ITERATIONS);
	let jsMedian, reference;
	for (const impl of impls) {
		process.stderr.write(`${c.label} / ${impl.name} ... `);
		const r = measure(impl.cmd, [...impl.args, path, JSON.stringify(c.config), iterations]);
		if (r.timeout) {
			process.stderr.write('timeout\n');
			lines.push(`| ${c.label} | ${impl.name} | > ${TIMEOUT_MS / 60000} min | | | | |`);
			continue;
		}
		const med = median(r.times);
		process.stderr.write(`${fmtMs(med)}\n`);
		jsMedian ??= med;
		reference ??= r;
		const same = r.checksum === reference.checksum && r.rows === reference.rows && r.errors === reference.errors;
		lines.push(`| ${c.label} | ${impl.name} | ${fmtMs(med)} | ${(mb / (med / 1000)).toFixed(0)} MB/s | ${(jsMedian / med).toFixed(2)}× | ${(r.rss / 2 ** 20).toFixed(0)} MB | ${same ? `✅ ${r.rows} rows` : `❌ rows ${r.rows}, errors ${r.errors}, ${r.checksum}`} |`);
	}
}

const table = lines.join('\n');
console.log(table);
writeFileSync(join(here, 'RESULTS.md'), `# Benchmark results\n\nGenerated by \`just bench-compare\`.\n\n${table}\n`);
